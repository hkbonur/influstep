import { MEDIA_BUDGET } from '@influstep/shared'
import { describe, expect, it } from 'vitest'
import { api, internal } from './_generated/api'
import type { Id } from './_generated/dataModel'
import { approveEpisode } from './core/episodes'
import { setup } from '../test/setup'

type Test = ReturnType<typeof setup>

async function seededAda(t: Test): Promise<Id<'personas'>> {
  await t.action(internal.internal.seed.run, { appUrl: 'http://localhost:3300' })
  await t.finishAllScheduledFunctions(() => {})
  const ada = (await t.query(api.private.personas.list, {})).find((persona) => persona.handle === 'ada.automates')
  if (!ada) throw new Error('the seed has no Ada')
  return ada._id
}

/** One of Ada's ideas written with a beat that asks for a generated still, as the writer stores it. */
async function writeWithPicture(t: Test, personaId: Id<'personas'>, prompt: string): Promise<Id<'episodes'>> {
  const idea = await t.run(async (ctx) =>
    (
      await ctx.db
        .query('episodes')
        .withIndex('by_persona', (q) => q.eq('personaId', personaId))
        .collect()
    ).find((episode) => episode.status === 'idea' && episode.kind === 'video')
  )
  if (!idea) throw new Error('Ada has no video idea')
  await t.mutation(internal.internal.agents.storeScript, {
    episodeId: idea._id,
    title: 'Why your retries never fire',
    description: 'A retry that never fires, and the one setting that fixes it.',
    shotPlan: [
      { title: 'Hook', voiceover: 'Your retries never fire. Here is why.', tool: 'Presenter', url: '' },
      {
        title: 'The failure',
        voiceover: 'Every run failed, and nobody saw it.',
        tool: 'n8n',
        url: 'http://localhost:5678',
        generate: { kind: 'image', prompt },
      },
      { title: 'The fix', voiceover: 'Turn on the error workflow and set a retry.', tool: 'n8n', url: 'http://localhost:5678' },
    ],
    autoApprove: false,
  })
  return idea._id
}

describe('generated media', () => {
  it('makes the picture a beat asks for, keeps it as the producer’s, and holds approval until it is in place', async () => {
    const t = setup()
    const adaId = await seededAda(t)
    const episodeId = await writeWithPicture(t, adaId, 'A run history where every execution fails in red')

    const written = await t.run(async (ctx) => ctx.db.get(episodeId))
    expect(written?.shotPlan?.[1]?.generate?.generationId).toBeDefined()
    await expect(t.run(async (ctx) => approveEpisode(ctx, episodeId))).rejects.toThrow(
      'The producer is still making the picture for beat 2; approve once it is made.'
    )

    await t.finishAllScheduledFunctions(() => {})
    const made = await t.run(async (ctx) => ctx.db.get(episodeId))
    const assetId = made?.shotPlan?.[1]?.assetId
    if (!assetId) throw new Error('the beat shows no picture')
    expect(made?.shots[1]).toMatchObject({ kind: 'asset', assetId })
    const asset = await t.run(async (ctx) => ctx.db.get(assetId))
    expect(asset).toMatchObject({
      source: 'producer',
      kind: 'image',
      episodeId,
      tags: ['generated'],
      name: 'A run history where every execution fails in red',
      note: 'Generated by mock from: "A run history where every execution fails in red"',
    })
    // In place, the picture no longer holds approval back.
    await t.run(async (ctx) => approveEpisode(ctx, episodeId))
  })

  it('says why a picture could not be made, and makes it again on the beat', async () => {
    const t = setup()
    const adaId = await seededAda(t)
    // Spend the day's images first, so the beat's picture is refused by the budget.
    await t.run(async (ctx) => {
      for (let n = 0; n < MEDIA_BUDGET.images; n += 1) {
        await ctx.db.insert('generations', {
          personaId: adaId,
          kind: 'image',
          prompt: `picture ${n}`,
          status: 'done',
          seconds: 0,
          createdAt: Date.now(),
          startedAt: Date.now(),
        })
      }
    })
    const episodeId = await writeWithPicture(t, adaId, 'A calendar with every Friday crossed out')
    await t.finishAllScheduledFunctions(() => {})
    const jobs = await t.run(async (ctx) =>
      (
        await ctx.db
          .query('jobs')
          .withIndex('by_persona_kind', (q) => q.eq('personaId', adaId).eq('kind', 'generate_media'))
          .collect()
      ).map((job) => [job.status, job.error])
    )
    expect(jobs).toEqual([['failed', expect.stringContaining('budget of 12 images is spent')]])
    await expect(t.run(async (ctx) => approveEpisode(ctx, episodeId))).rejects.toThrow(
      /The picture for beat 2 could not be made: Today's budget/
    )
    // The episode itself did not fail: only its picture.
    expect((await t.run(async (ctx) => ctx.db.get(episodeId)))?.status).toBe('scripted')

    // The budget resets; here, the spent ones are taken back, and the beat asks again.
    await t.run(async (ctx) => {
      for (const generation of await ctx.db.query('generations').collect())
        if (generation.episodeId === undefined) await ctx.db.delete(generation._id)
    })
    await t.mutation(api.private.media.regenerateForBeat, { episodeId, beatIndex: 1 })
    await t.finishAllScheduledFunctions(() => {})
    expect((await t.run(async (ctx) => ctx.db.get(episodeId)))?.shotPlan?.[1]?.assetId).toBeDefined()
  })

  it('generates for the operator on the Assets page, within the prompt rules, and again from an asset’s prompt', async () => {
    const t = setup()
    const adaId = await seededAda(t)
    await expect(
      t.mutation(api.private.media.generate, { personaId: adaId, kind: 'image', prompt: 'The n8n canvas with a red node' })
    ).rejects.toThrow('The prompt names n8n, a brand other than Formstep')
    await t.mutation(api.private.media.generate, { personaId: adaId, kind: 'clip', prompt: 'A paper plane that never lands' })
    await t.finishAllScheduledFunctions(() => {})
    const view = await t.query(api.private.media.forPersona, { personaId: adaId })
    expect(view?.spent).toEqual({ images: 0, clipSeconds: 5 })
    expect(view?.generations).toEqual([])
    const [made] = view?.assetPrompts ?? []
    if (!made) throw new Error('nothing was generated')
    expect(made.prompt).toBe('A paper plane that never lands')

    await t.mutation(api.private.media.regenerateAsset, { assetId: made.assetId })
    await t.finishAllScheduledFunctions(() => {})
    const library = await t.query(api.private.assets.list, { personaId: adaId })
    expect(library?.assets.filter((asset) => asset.tags.includes('generated')).map((asset) => asset.name)).toEqual([
      'A paper plane that never lands',
      'A paper plane that never lands',
    ])
    expect((await t.query(api.private.media.forPersona, { personaId: adaId }))?.spent.clipSeconds).toBe(10)
  })

  it('draws a portrait for the look from the Assets page, and a new one leads the look when it is made again', async () => {
    const t = setup()
    const adaId = await seededAda(t)
    await t.mutation(api.private.media.generatePortrait, { personaId: adaId, description: 'Calm, late thirties, dark bob, grey cardigan.' })
    await t.finishAllScheduledFunctions(() => {})
    const first = (await t.run(async (ctx) => ctx.db.get(adaId)))?.appearance?.referenceAssetIds[0]
    if (!first) throw new Error('no portrait')
    expect(await t.run(async (ctx) => ctx.db.get(first))).toMatchObject({
      name: 'Portrait of Ada Automates',
      tags: ['generated', 'reference'],
    })

    await t.mutation(api.private.media.regenerateAsset, { assetId: first })
    await t.finishAllScheduledFunctions(() => {})
    const references = (await t.run(async (ctx) => ctx.db.get(adaId)))?.appearance?.referenceAssetIds ?? []
    expect(references).toHaveLength(2)
    expect(references[1]).toBe(first)
  })
})
